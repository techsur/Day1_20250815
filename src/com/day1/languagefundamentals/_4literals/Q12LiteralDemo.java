package com.day1.languagefundamentals._4literals;

public class Q12LiteralDemo {

	public static void main(String[] args) {
		// Integer literal
		int intLiteral = 100; // 100 is an int literal
		// Float literal
		float floatLiteral = 12.5f; // 12.5f or 12.5F denotes a float literal
		// Double literal
		double doubleLiteral = 123.456; // 123.456 is a double literal by default
		// Boolean literal
		boolean booleanLiteral = true; // true or false
		// Char literal
		char charLiteral = 'A'; // single character in single quotes
		// String literal
		String stringLiteral = "Hello Java"; // sequence of characters in double quotes

		// Printing literals
		System.out.println("Integer literal: " + intLiteral); // Output: 100
		System.out.println("Float literal: " + floatLiteral); // Output: 12.5
		System.out.println("Double literal: " + doubleLiteral); // Output: 123.456
		System.out.println("Boolean literal: " + booleanLiteral); // Output: true
		System.out.println("Char literal: " + charLiteral); // Output: A
		System.out.println("String literal: " + stringLiteral); // Output: Hello Java
	}
}
